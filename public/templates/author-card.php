<?php
/**
 * Author card template.
 *
 * Available variables: $args (array) with an `author` key.
 *
 * This file can be overridden by copying it to
 * yourtheme/author-content-manager/author-card.php.
 *
 * @package AuthorContentManager
 */

defined( 'ABSPATH' ) || exit;

$acm_author = isset( $args['author'] ) ? $args['author'] : null;

if ( ! $acm_author instanceof ACM_Author || ! $acm_author->exists() ) {
	return;
}

$acm_name        = $acm_author->get_name();
$acm_profile_url = $acm_author->get_profile_url();
$acm_photo       = ! empty( $args['show_image'] ) ? $acm_author->get_photo_html( isset( $args['image_size'] ) ? $args['image_size'] : '', array( 'class' => 'acm-author-card__photo' ) ) : '';
$acm_bio         = ! empty( $args['show_bio'] ) ? $acm_author->get_bio_short( array_key_exists( 'bio_limit', $args ) ? $args['bio_limit'] : null ) : '';
$acm_social      = ! empty( $args['show_social'] ) ? $acm_author->get_social_links() : array();
$acm_contact     = ! empty( $args['show_contact'] ) ? $acm_author->get_contact_items() : array();
$acm_show_link   = ! empty( $args['show_link'] ) && '' !== $acm_profile_url;
$acm_classes     = array( 'acm-author-card' );

if ( ! empty( $args['class'] ) ) {
	$acm_classes[] = $args['class'];
}

if ( '' === $acm_name && '' === $acm_photo && '' === $acm_bio && empty( $acm_contact ) && empty( $acm_social ) && ! $acm_show_link ) {
	return;
}
?>
<article class="<?php echo esc_attr( implode( ' ', $acm_classes ) ); ?>">
	<?php if ( '' !== $acm_photo ) : ?>
		<div class="acm-author-card__media">
			<?php if ( '' !== $acm_profile_url ) : ?>
				<a class="acm-author-card__media-link" href="<?php echo esc_url( $acm_profile_url ); ?>" tabindex="-1" aria-hidden="true" data-acm-profile-link="1">
					<?php echo $acm_photo; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Markup generated by wp_get_attachment_image(). ?>
				</a>
			<?php else : ?>
				<?php echo $acm_photo; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Markup generated by wp_get_attachment_image(). ?>
			<?php endif; ?>
		</div>
	<?php endif; ?>

	<div class="acm-author-card__body">
		<?php if ( '' !== $acm_name ) : ?>
			<h3 class="acm-author-card__name">
				<?php if ( '' !== $acm_profile_url ) : ?>
					<a href="<?php echo esc_url( $acm_profile_url ); ?>"><?php echo esc_html( $acm_name ); ?></a>
				<?php else : ?>
					<?php echo esc_html( $acm_name ); ?>
				<?php endif; ?>
			</h3>
		<?php endif; ?>

		<?php if ( ! empty( $acm_social ) ) : ?>
			<ul class="acm-author-card__social">
				<?php foreach ( $acm_social as $acm_link ) : ?>
					<li class="acm-author-card__social-item">
						<a
							class="acm-author-card__social-link acm-author-card__social-link--<?php echo esc_attr( $acm_link['key'] ); ?>"
							href="<?php echo esc_url( $acm_link['url'] ); ?>"
							target="_blank"
							rel="noopener noreferrer nofollow"
						>
							<?php echo ACM_Templates::icon( $acm_link['key'] ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Static SVG markup. ?>
							<span class="acm-author-card__social-label"><?php echo esc_html( $acm_link['label'] ); ?></span>
						</a>
					</li>
				<?php endforeach; ?>
			</ul>
		<?php endif; ?>

		<?php if ( '' !== $acm_bio ) : ?>
			<p class="acm-author-card__bio"><?php echo esc_html( $acm_bio ); ?></p>
		<?php endif; ?>

		<?php if ( ! empty( $acm_contact ) ) : ?>
			<ul class="acm-author-card__contact">
				<?php foreach ( $acm_contact as $acm_item ) : ?>
					<li class="acm-author-card__contact-item acm-author-card__contact-item--<?php echo esc_attr( $acm_item['key'] ); ?>">
						<span class="acm-author-card__contact-label"><?php echo esc_html( $acm_item['label'] ); ?>:</span>
						<span class="acm-author-card__contact-value">
							<?php echo ACM_Templates::contact_value_html( $acm_item ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Escaped inside the helper. ?>
						</span>
					</li>
				<?php endforeach; ?>
			</ul>
		<?php endif; ?>

		<?php if ( $acm_show_link ) : ?>
			<a class="acm-author-card__link" href="<?php echo esc_url( $acm_profile_url ); ?>">
				<?php esc_html_e( 'View profile', 'author-content-manager' ); ?>
				<span aria-hidden="true">&rarr;</span>
				<span class="screen-reader-text"><?php echo esc_html( sprintf( /* translators: %s: author name. */ __( 'of %s', 'author-content-manager' ), $acm_name ) ); ?></span>
			</a>
		<?php endif; ?>
	</div>
</article>

<?php
/**
 * Individual author profile template.
 *
 * Available variables: $args with an `author` key and display settings.
 *
 * This file can be overridden by copying it to
 * yourtheme/author-content-manager/author-profile.php.
 *
 * @package AuthorContentManager
 */

defined( 'ABSPATH' ) || exit;

$acm_author = isset( $args['author'] ) ? $args['author'] : null;

if ( ! $acm_author instanceof ACM_Author || ! $acm_author->exists() ) {
	return;
}

$acm_name        = $acm_author->get_name();
$acm_profile_url = $acm_author->get_profile_url();
$acm_photo       = ! empty( $args['show_image'] ) ? $acm_author->get_photo_html( isset( $args['image_size'] ) ? $args['image_size'] : '', array( 'class' => 'acm-author__photo-img' ) ) : '';
$acm_bio         = ! empty( $args['show_bio'] ) ? $acm_author->get_bio_html() : '';
$acm_social      = ! empty( $args['show_social'] ) ? $acm_author->get_social_links() : array();
$acm_contact     = ! empty( $args['show_contact'] ) ? $acm_author->get_contact_items() : array();
$acm_custom      = ! empty( $args['show_custom'] ) ? $acm_author->get_custom_fields( true ) : array();
$acm_layout      = isset( $args['layout'] ) && 'horizontal' === $args['layout'] ? 'horizontal' : 'vertical';
$acm_context     = isset( $args['context'] ) ? $args['context'] : 'shortcode';
$acm_classes     = array( 'acm-author', 'acm-author--' . $acm_layout );

if ( ! empty( $args['class'] ) ) {
	$acm_classes[] = $args['class'];
}

$acm_link_name = '' !== $acm_profile_url && 'single' !== $acm_context;

if ( '' === $acm_photo && '' === $acm_bio && '' === $acm_name && empty( $acm_contact ) && empty( $acm_social ) && empty( $acm_custom ) ) {
	return;
}
?>
<div class="<?php echo esc_attr( implode( ' ', $acm_classes ) ); ?>" data-acm-author-id="<?php echo esc_attr( (string) $acm_author->get_id() ); ?>">
	<?php if ( '' !== $acm_photo ) : ?>
		<div class="acm-author__media">
			<?php echo $acm_photo; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Markup generated by wp_get_attachment_image(). ?>
		</div>
	<?php endif; ?>

	<div class="acm-author__body">
		<?php if ( '' !== $acm_name && ! empty( $args['show_name'] ) ) : ?>
			<h2 class="acm-author__name">
				<?php if ( $acm_link_name ) : ?>
					<a href="<?php echo esc_url( $acm_profile_url ); ?>"><?php echo esc_html( $acm_name ); ?></a>
				<?php else : ?>
					<?php echo esc_html( $acm_name ); ?>
				<?php endif; ?>
			</h2>
		<?php endif; ?>

		<?php if ( ! empty( $acm_social ) ) : ?>
			<ul class="acm-author__social">
				<?php foreach ( $acm_social as $acm_link ) : ?>
					<li class="acm-author__social-item">
						<a
							class="acm-author__social-link acm-author__social-link--<?php echo esc_attr( $acm_link['key'] ); ?>"
							href="<?php echo esc_url( $acm_link['url'] ); ?>"
							target="_blank"
							rel="noopener noreferrer nofollow"
						>
							<?php echo ACM_Templates::icon( $acm_link['key'] ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Static SVG markup. ?>
							<span class="acm-author__social-label"><?php echo esc_html( $acm_link['label'] ); ?></span>
						</a>
					</li>
				<?php endforeach; ?>
			</ul>
		<?php endif; ?>

		<?php if ( '' !== $acm_bio ) : ?>
			<div class="acm-author__bio"><?php echo wp_kses_post( $acm_bio ); ?></div>
		<?php endif; ?>

		<?php if ( ! empty( $acm_contact ) ) : ?>
			<dl class="acm-author__contact">
				<?php foreach ( $acm_contact as $acm_item ) : ?>
					<div class="acm-author__contact-row acm-author__contact-row--<?php echo esc_attr( $acm_item['key'] ); ?>">
						<dt class="acm-author__contact-label">
							<?php
							$acm_icon = ACM_Templates::contact_icon( $acm_item['key'] );

							if ( '' !== $acm_icon ) {
								echo ACM_Templates::icon( $acm_icon ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Static SVG markup.
							}
							?>
							<span class="acm-author__contact-text"><?php echo esc_html( $acm_item['label'] ); ?></span>
						</dt>
						<dd class="acm-author__contact-value">
							<?php echo ACM_Templates::contact_value_html( $acm_item ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Escaped inside the helper. ?>
						</dd>
					</div>
				<?php endforeach; ?>
			</dl>
		<?php endif; ?>

		<?php if ( ! empty( $acm_custom ) ) : ?>
			<?php
			echo ACM_Custom_Fields::render_list( // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Escaped inside the renderer.
				$acm_custom,
				array(
					'context'     => 'author',
					'class'       => 'acm-author__custom',
					'show_labels' => true,
				)
			);
			?>
		<?php endif; ?>
	</div>
</div>

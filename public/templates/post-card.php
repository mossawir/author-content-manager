<?php
/**
 * Post card template used by post-grid.php and post-list.php.
 *
 * Available variables: $args with `post` and the display settings.
 *
 * This file can be overridden by copying it to
 * yourtheme/author-content-manager/post-card.php.
 *
 * @package AuthorContentManager
 */

defined( 'ABSPATH' ) || exit;

$acm_post = isset( $args['post'] ) ? $args['post'] : null;

if ( ! $acm_post instanceof WP_Post ) {
	return;
}

$acm_layout      = isset( $args['layout'] ) && 'list' === $args['layout'] ? 'list' : 'grid';
$acm_title       = get_the_title( $acm_post );
$acm_permalink   = get_permalink( $acm_post );
$acm_image       = '';
$acm_terms       = array();
$acm_date        = '';
$acm_date_iso    = '';
$acm_excerpt     = '';
$acm_read_more   = false;
$acm_image_size  = isset( $args['image_size'] ) ? $args['image_size'] : 'medium';
$acm_taxonomy    = isset( $args['taxonomy'] ) ? (string) $args['taxonomy'] : '';

if ( ! empty( $args['show_image'] ) && has_post_thumbnail( $acm_post ) ) {
	$acm_image = get_the_post_thumbnail(
		$acm_post,
		$acm_image_size,
		array(
			'class'    => 'acm-post-card__image',
			'alt'      => $acm_title,
			'loading'  => 'lazy',
			'decoding' => 'async',
		)
	);

	$acm_image = is_string( $acm_image ) ? $acm_image : '';
}

if ( ! empty( $args['show_terms'] ) && '' !== $acm_taxonomy ) {
	$acm_found = get_the_terms( $acm_post, $acm_taxonomy );

	if ( is_array( $acm_found ) ) {
		$acm_terms = $acm_found;
	}
}

if ( ! empty( $args['show_date'] ) ) {
	$acm_date     = get_the_date( '', $acm_post );
	$acm_date_iso = get_the_date( 'c', $acm_post );
}

if ( ! empty( $args['show_excerpt'] ) ) {
	$acm_excerpt = get_the_excerpt( $acm_post );

	if ( '' !== trim( (string) $acm_excerpt ) ) {
		$acm_excerpt = trim( wp_strip_all_tags( $acm_excerpt ) );

		$acm_length = isset( $args['excerpt_length'] ) ? (int) $args['excerpt_length'] : 20;

		if ( $acm_length > 0 ) {
			$acm_excerpt = wp_trim_words( $acm_excerpt, $acm_length, '…' );
		}
	}
}

if ( ! empty( $args['show_read_more'] ) && '' !== $acm_permalink ) {
	$acm_read_more = true;
}

if ( '' === $acm_title && '' === $acm_image && '' === $acm_excerpt && '' === $acm_date && empty( $acm_terms ) && ! $acm_read_more ) {
	return;
}

$acm_classes = array( 'acm-post-card', 'acm-post-card--' . $acm_layout );
$acm_terms_html = array();

foreach ( $acm_terms as $acm_term ) {
	$acm_term_link = get_term_link( $acm_term );

	if ( is_wp_error( $acm_term_link ) ) {
		continue;
	}

	$acm_terms_html[] = '<li class="acm-post-card__term"><a href="' . esc_url( $acm_term_link ) . '">' . esc_html( $acm_term->name ) . '</a></li>';
}
?>
<article class="<?php echo esc_attr( implode( ' ', $acm_classes ) ); ?>" data-acm-post-id="<?php echo esc_attr( (string) $acm_post->ID ); ?>">
	<?php if ( '' !== $acm_image ) : ?>
		<div class="acm-post-card__media">
			<?php if ( '' !== $acm_permalink ) : ?>
				<a class="acm-post-card__media-link" href="<?php echo esc_url( $acm_permalink ); ?>" tabindex="-1" aria-hidden="true">
					<?php echo $acm_image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Markup generated by get_the_post_thumbnail(). ?>
				</a>
			<?php else : ?>
				<?php echo $acm_image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Markup generated by get_the_post_thumbnail(). ?>
			<?php endif; ?>
		</div>
	<?php endif; ?>

	<div class="acm-post-card__body">
		<?php if ( ! empty( $acm_terms_html ) ) : ?>
			<ul class="acm-post-card__terms">
				<?php echo implode( '', $acm_terms_html ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Built from escaped values above. ?>
			</ul>
		<?php endif; ?>

		<?php if ( '' !== $acm_title ) : ?>
			<h3 class="acm-post-card__title">
				<?php if ( '' !== $acm_permalink ) : ?>
					<a href="<?php echo esc_url( $acm_permalink ); ?>"><?php echo esc_html( $acm_title ); ?></a>
				<?php else : ?>
					<?php echo esc_html( $acm_title ); ?>
				<?php endif; ?>
			</h3>
		<?php endif; ?>

		<?php if ( '' !== $acm_date ) : ?>
			<p class="acm-post-card__meta">
				<time class="acm-post-card__date" datetime="<?php echo esc_attr( $acm_date_iso ); ?>"><?php echo esc_html( $acm_date ); ?></time>
			</p>
		<?php endif; ?>

		<?php if ( '' !== $acm_excerpt ) : ?>
			<p class="acm-post-card__excerpt"><?php echo esc_html( $acm_excerpt ); ?></p>
		<?php endif; ?>

		<?php if ( $acm_read_more ) : ?>
			<a class="acm-post-card__link" href="<?php echo esc_url( $acm_permalink ); ?>">
				<?php esc_html_e( 'Read more', 'author-content-manager' ); ?>
				<span aria-hidden="true">&rarr;</span>
				<span class="screen-reader-text">
					<?php
					printf(
						/* translators: %s: post title. */
						esc_html__( 'about %s', 'author-content-manager' ),
						esc_html( $acm_title )
					);
					?>
				</span>
			</a>
		<?php endif; ?>
	</div>
</article>
